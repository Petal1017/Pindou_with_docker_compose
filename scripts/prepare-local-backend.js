import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const envPath = resolve(root, '.env.local')
const supabaseCli = resolve(root, 'node_modules', 'supabase', 'dist', 'supabase.js')
const envOnly = process.argv.includes('--env-only')

function runSupabase(args, options = {}) {
  return execFileSync(
    process.execPath,
    [supabaseCli, ...args],
    { cwd: root, encoding: 'utf8', stdio: options.capture ? ['ignore', 'pipe', 'pipe'] : 'inherit' },
  )
}

if (!envOnly) {
  console.log('Starting the local Supabase backend...')
  runSupabase(['start'])
}

let status
try {
  status = runSupabase(['status', '-o', 'env'], { capture: true })
} catch (error) {
  const details = error.stderr?.trim() || error.message
  console.error(`Local Supabase is not available: ${details}`)
  console.error('Start Docker Desktop, then run npm run dev:local again.')
  process.exit(1)
}

const values = Object.fromEntries(
  status.split(/\r?\n/).flatMap((line) => {
    const match = line.match(/^([A-Z0-9_]+)=(?:"(.*)"|(.*))$/)
    return match ? [[match[1], match[2] ?? match[3] ?? '']] : []
  }),
)

if (!values.API_URL || !values.ANON_KEY) {
  console.error('Could not read API_URL and ANON_KEY from `supabase status -o env`.')
  process.exit(1)
}

const managed = [
  '# Generated by npm run dev:local. Do not commit.',
  `VITE_SUPABASE_URL=${values.API_URL}`,
  `VITE_SUPABASE_ANON_KEY=${values.ANON_KEY}`,
  'VITE_TURNSTILE_SITE_KEY=',
  '',
].join('\n')

if (!existsSync(envPath) || readFileSync(envPath, 'utf8') !== managed) {
  writeFileSync(envPath, managed, 'utf8')
  console.log(`Wrote ${envPath}`)
}

console.log(`Local API: ${values.API_URL}`)
console.log('Local Studio: http://127.0.0.1:54323')
console.log('Local email inbox: http://127.0.0.1:54324')
